"""Build the existing Creative Checker HTML report format from verified evidence."""
from pathlib import Path
from datetime import datetime, timezone
from html import escape
import argparse
import base64
import importlib.util
import json
import math
import os

from resultlib import (LABELS, LABEL_NAMES, RUNS, inside, read, require, save, sha,
                       verify_results, write_csv)

HERE = Path(__file__).resolve().parent
MODEL_NAMES = {'siglip2': 'SigLIP2 고정 + 분류층', 'convnextv2': 'ConvNeXt V2 고정 + 분류층',
               'siglip2_frozen': 'SigLIP2 고정 · 재측정', 'siglip2_full_finetune': 'SigLIP2 본체 파인튜닝',
               'siglip2_focused': 'SigLIP2 개선 실험 선택 모델'}


def table(headers, rows):
    return '<div class="table-wrap"><table><thead><tr>' + ''.join('<th scope="col">' + escape(str(v)) + '</th>' for v in headers) + '</tr></thead><tbody>' + ''.join(
        '<tr>' + ''.join('<td>' + escape(str(v)) + '</td>' for v in row) + '</tr>' for row in rows) + '</tbody></table></div>'


def figures(data, output):
    """Optional plots use an already-installed matplotlib; never install it."""
    if importlib.util.find_spec('matplotlib') is None:
        return {}, 'matplotlib 미설치: 표와 원시 CSV를 생성했으며 그래프는 생략했습니다. 패키지 설치는 수행하지 않았습니다.'
    os.environ.setdefault('MPLCONFIGDIR', str(output / 'mpl-cache'))
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib import font_manager
    for font in (Path('/System/Library/Fonts/AppleSDGothicNeo.ttc'), Path('C:/Windows/Fonts/malgun.ttf')):
        if font.is_file():
            font_manager.fontManager.addfont(str(font))
            plt.rcParams['font.family'] = font_manager.FontProperties(fname=str(font)).get_name()
            break
    plt.rcParams.update({'font.size': 10, 'axes.unicode_minus': False, 'svg.fonttype': 'none'})
    models = data['models']; names = [f'{i + 1}. {m["model"]}' for i, m in enumerate(models)]
    paths = {}
    def finish(fig, key):
        fig.tight_layout()
        path = output / (key + '.svg')
        fig.savefig(path, format='svg', metadata={'Date': None})
        plt.close(fig); paths[key] = path.name
    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    axes[0].barh(names, [m['metrics']['label_wise_accuracy'] * 100 for m in models], color='#315b48')
    axes[0].axvline(90, color='#ac754a', linestyle='--'); axes[0].set_xlim(0, 100); axes[0].set_xlabel('Label-wise accuracy (%)')
    axes[1].barh(names, [m['timing']['total_ms']['p95_ms'] for m in models], color='#a9b998')
    axes[1].axvline(50, color='#ac754a', linestyle='--'); axes[1].set_xlabel('p95 (ms / image)')
    finish(fig, 'accuracy-p95')
    for run in RUNS[1:]:
        fig, axis = plt.subplots(figsize=(10, 3.6))
        for candidate in data['candidates'][run]:
            axis.plot([r['epoch'] for r in candidate['history']], [r['dev_macro_AP'] for r in candidate['history']], marker='o', label=candidate['id'])
        axis.set_xlabel('Epoch'); axis.set_ylabel('Dev Macro AP'); axis.legend(fontsize=8); axis.grid(alpha=.2)
        finish(fig, 'learning-' + run)
    return paths, '그래프는 저장된 개발 지표·평가 원시 기록에서 생성했습니다.'


def build_report(evidence, output, title='SigLIP2 학습·평가 결과서', make_figures=True):
    evidence, output = Path(evidence).resolve(), Path(output).resolve()
    require(not output.exists(), 'Report output already exists; choose a new directory')
    require(not output.is_relative_to(evidence) and not evidence.is_relative_to(output), 'Report must be separate from immutable evidence')
    data = verify_results(evidence)
    output.mkdir(parents=True)
    # The verification file is generated by this run, never trusted from an earlier invocation.
    save(output / 'verification.json', data)
    data['report_generated_at_utc'] = datetime.now(timezone.utc).isoformat()
    data['title'] = title
    if data['dataset'].get('synthetic_test_fixture'):
        data['title'] = '합성 데이터 검증용 · ' + title
    plot_paths, plot_note = figures(data, output) if make_figures else ({}, '그래프 생략 옵션을 사용했습니다. 표·CSV와 검증 결과는 포함합니다.')
    data['figures'] = plot_paths
    primary = [m for m in data['models'] if m['run'] == RUNS[2]]
    before, after = primary
    metrics, timing = after['metrics'], after['timing']['total_ms']
    selected = data['selected']
    selection_text = ('새로 학습한 가중치 선택' if selected['source'] == 'trained' else
                      '기존 가중치 유지 · 원래 임계값' if selected['threshold_policy'] == 'original' else '기존 가중치 유지 · 개발셋 임계값 변경')
    needed = math.ceil(.9 * metrics['known_evaluated_cells'])
    correct = sum(v['tp'] + v['tn'] for v in after['confusion'].values())
    overall, labels = [], []
    for model in data['models']:
        m, t = model['metrics'], model['timing']['total_ms']
        overall.append(dict(run=model['run'], model=model['model'], accuracy=m['label_wise_accuracy'], macro_f1=m['macro_f1'],
                            mean_ms=t['mean_ms'], median_ms=t['median_ms'], p95_ms=t['p95_ms'], goal_met=model['goal_met']))
    for key, name in zip(LABELS, LABEL_NAMES):
        a, b = before['confusion'][key], after['confusion'][key]
        metric = after['metrics']['per_label'][key]
        labels.append(dict(label=key, name=name, prior_fp=a['fp'], focused_fp=b['fp'], fp_delta=b['fp'] - a['fp'],
                           prior_fn=a['fn'], focused_fn=b['fn'], fn_delta=b['fn'] - a['fn'],
                           precision=metric['precision'], recall=metric['recall'], f1=metric['f1']))
    write_csv(output / 'comparison.csv', overall)
    write_csv(output / 'per_label_comparison.csv', labels)
    write_csv(output / 'error_changes.csv', data['error_changes'], ('image_id', 'label', 'truth', 'prior_prediction', 'focused_prediction', 'change'))
    save(output / 'report-data.json', data)
    summary = f'<p class="lead">{escape(selection_text)}. 평가 정답 <strong>{correct}/{metrics["known_evaluated_cells"]}</strong>, 정확도 <strong>{metrics["label_wise_accuracy"]:.2%}</strong>, p95 <strong>{timing["p95_ms"]:.2f}ms</strong>입니다.</p>'
    summary += '<div class="grid three">' + ''.join(f'<div class="card"><span class="label">{name}</span><strong class="value">{value}</strong></div>' for name, value in (
        ('정확도 · 목표 90%', f'{metrics["label_wise_accuracy"]:.2%}'), ('p95 · 목표 50ms 이하', f'{timing["p95_ms"]:.2f} ms'), ('두 목표 동시 달성', '달성' if after['goal_met'] else '미달'))) + '</div>'
    summary += f'<p>90% 달성에 필요한 정답은 {needed}개이며 현재 대비 추가 {max(0, needed - correct)}개입니다. 정확도는 이미지 단위 전체 정답률이 아닌 알려진 라벨 항목 기준입니다.</p>'
    environment = data['environment']
    protocol = table(['항목', '내용'], [
        ['데이터', '학습113 / 개발37 / 평가37 · known282 / unknown14 제외'],
        ['라벨 승인', data['dataset'].get('approval_qualification', '사용자가 승인한 AI 보조 라벨')],
        ['장비', environment.get('GPU', '미기록')], ['실행 환경', json.dumps(environment.get('versions', {}), ensure_ascii=False)],
        ['측정', 'FP32 · batch1 · 이미지 디코딩/전처리/전송/비전 모델/분류층'],
        ['제외', 'OCR · 네트워크 · API · DB · 모델 로딩 · 워밍업 · 학습'],
        ['선택', selected['id'] + ' / ' + selected['threshold_policy'] + ' / epoch ' + str(selected['best_epoch'])],
        ['임계값', json.dumps(selected['thresholds'])]])
    results = table(['실행', '모델', '정확도', 'Macro F1', '평균ms', '중앙ms', 'p95ms', '목표'],
        [[r['run'], MODEL_NAMES.get(r['model'], r['model']), f'{r["accuracy"]:.2%}', f'{r["macro_f1"]:.4f}', f'{r["mean_ms"]:.2f}', f'{r["median_ms"]:.2f}', f'{r["p95_ms"]:.2f}', '달성' if r['goal_met'] else '미달'] for r in overall])
    results += f'<p class="muted">{escape(plot_note)} 실행이 다른 행의 시간은 측정 시점이 다른 관측값입니다. 이번 개선 효과는 siglip-focused-fp32 내부의 두 행으로 비교합니다.</p>'
    for key in ('accuracy-p95',):
        if key in plot_paths:
            results += f'<figure><img src="{plot_paths[key]}" alt="모델별 정확도와 p95 비교"><figcaption>점선은 정확도90%, p95 50ms 목표입니다.</figcaption></figure>'
    delta = table(['이번 실행의 비교 항목', '이전 본체 파인튜닝', '선택 모델', '차이'], [
        ['정확도', f'{before["metrics"]["label_wise_accuracy"]:.2%}', f'{metrics["label_wise_accuracy"]:.2%}', f'{(metrics["label_wise_accuracy"] - before["metrics"]["label_wise_accuracy"]) * 100:+.2f} %p'],
        ['Macro F1', f'{before["metrics"]["macro_f1"]:.4f}', f'{metrics["macro_f1"]:.4f}', f'{metrics["macro_f1"] - before["metrics"]["macro_f1"]:+.4f}'],
        ['p95', f'{before["timing"]["total_ms"]["p95_ms"]:.2f}ms', f'{timing["p95_ms"]:.2f}ms', f'{timing["p95_ms"] - before["timing"]["total_ms"]["p95_ms"]:+.2f}ms']])
    delta += '<p>같은 이미지의 반복 측정이며 작은 시간 차이만으로 모델의 속도 우열을 확정하지 않습니다. 기존 모델을 유지한 경우 새 가중치 학습의 개선으로 해석하지 않습니다.</p>'
    label_table = table(['라벨', '이전FP → 선택FP', 'FP 차이', '이전FN → 선택FN', 'FN 차이', '정밀도', '재현율', 'F1'],
        [[r['name'], f'{r["prior_fp"]} → {r["focused_fp"]}', f'{r["fp_delta"]:+d}', f'{r["prior_fn"]} → {r["focused_fn"]}', f'{r["fn_delta"]:+d}', f'{r["precision"]:.3f}', f'{r["recall"]:.3f}', f'{r["f1"]:.3f}'] for r in labels])
    learning = '<p>체크포인트는 개발 Macro AP, 최종 모델·임계값은 개발 지표와 보호 조건으로 선택했습니다. 평가 결과로 설정을 다시 고르지 않습니다.</p>'
    for run in RUNS[1:]:
        learning += '<h3>' + escape(run) + '</h3>' + table(['후보', '선택 epoch', '학습 epoch 수', '본체 LR'],
            [[c['id'], c['best_epoch'], len(c['history']), c['settings']['backbone_lr']] for c in data['candidates'][run]])
        if 'learning-' + run in plot_paths:
            learning += f'<figure><img src="{plot_paths["learning-" + run]}" alt="{run} 개발 Macro AP 학습 곡선"></figure>'
    cases = render_cases(evidence, data)
    validation = table(['확인 항목', '결과'], [
        ['파일 SHA256 / 선택 commit / 프로토콜·소스 fingerprint', '확인'], ['동일 이미지·라벨·미확정 마스크 / 개발 선택 재계산', '확인'],
        ['저장 예측으로 정확도·F1·AP / timing_raw로 p50·p95 재계산', '확인'],
        ['가중치 파일 바이트', '포함 파일의 해시 확인' if data['checkpoint_bytes_verified'] else '보고서 경량 묶음에서 제외'],
        ['본체 가중치 변화의 독립 검증 / GPU 재추론', '수행하지 않음 · 학습 시 저장한 gradient/가중치 변화 기록만 확인'],
        ['증거 묶음 manifest SHA256', data['manifest_sha256']]])
    limitations = '<ul><li>동일 평가37장을 재사용한 후속 비교입니다. 새로운 독립 일반화 성능으로 해석하지 않습니다.</li><li>목표는 정확도90% 이상과 p95 50ms 이하입니다. 공통 실행기의 중앙값30ms 추가 조건은 이 보고서의 목표 판정에 사용하지 않습니다.</li><li>오류 사례는 저장 예측과 정답 라벨의 차이입니다. 이미지별 실패 원인을 자동으로 확정하거나 라벨을 수정하지 않습니다.</li><li>보고서 파일과 모델 백업은 별개입니다. 가중치가 제외된 묶음으로 배포 모델 복원을 확인했다고 보고하지 않습니다.</li></ul>'
    sections = [('summary', '결과 요약', summary), ('protocol', '실험 조건과 기준', protocol), ('results', '정확도와 처리 시간', results),
                ('deltas', '이전 모델 대비 변화', delta), ('labels', '라벨별 오탐·누락', label_table), ('learning', '개발셋 선택과 학습 이력', learning),
                ('cases', '오류 이미지와 개선·퇴행', cases), ('validation', '검증과 원본 근거', validation), ('limits', '평가 한계와 해석', limitations)]
    navigation = ''.join(f'<a href="#{key}"><span>{i:02}</span>{heading}</a>' for i, (key, heading, _) in enumerate(sections, 1))
    body = ''.join(f'<section id="{key}" class="doc-panel"><div class="eyebrow">SECTION {i:02}</div><h2>{heading}</h2>{content}</section>' for i, (key, heading, content) in enumerate(sections, 1))
    css = (HERE / 'result_report.css').read_text(encoding='utf-8')
    html = '<!doctype html><html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>' + escape(data['title']) + '</title><style>' + css + '</style></head><body>'
    html += '<a class="skip" href="#summary">본문 바로가기</a><header class="site-head"><div class="brand-row"><a class="brand" href="#summary">크리에이티브체커<small>CREATIVE CHECKER · EXPERIMENT REPORT</small></a><div class="actions"><button type="button" onclick="window.print()">인쇄 · PDF 저장</button><a href="comparison.csv">비교 CSV</a><a href="report-data.json">원본 지표 JSON</a></div></div></header>'
    html += '<div class="hero"><div class="eyebrow">VERIFIED RUNPOD RESULTS</div><h1>' + escape(data['title']) + '</h1><p class="hero-lead">완료된 실험 산출물을 작업 PC에서 검증한 학습·평가 결과서</p><p class="meta">생성 UTC ' + escape(data['report_generated_at_utc']) + '</p></div>'
    html += '<div class="layout"><aside class="side"><nav class="toc" aria-label="보고서 목차">' + navigation + '</nav></aside><main>' + body + '</main></div><footer>원본 증거는 별도 보존합니다. GPU 학습·추론을 다시 실행하지 않고 저장 결과를 검증했습니다.</footer></body></html>'
    (output / 'report.html').write_text(html, encoding='utf-8')
    save(output / 'report_manifest.json', {p.name: dict(bytes=p.stat().st_size, sha256=sha(p)) for p in output.iterdir() if p.is_file()})
    return output / 'report.html'


def render_cases(evidence, data):
    bundle = evidence / 'bundle'
    images = {r['image_id']: r for r in read(bundle / 'data/test.json')}
    primary = [m for m in data['models'] if m['run'] == RUNS[2]]
    rows = primary[1]['predictions']
    cases = {}
    for row in rows:
        errors = [LABEL_NAMES[j] + (' 오탐' if row['predictions'][j] else ' 누락') for j, label in enumerate(LABELS)
                  if row['labels'][label] is not None and row['labels'][label] != row['predictions'][j]]
        if errors:
            cases[row['image_id']] = errors
    for change in data['error_changes']:
        cases.setdefault(change['image_id'], []).append(LABEL_NAMES[LABELS.index(change['label'])] + (' 개선' if change['change'] == 'recovered' else ' 퇴행'))
    cards = []
    for image_id, descriptions in cases.items():
        path = inside(bundle, images[image_id]['image'])
        image = '<p class="muted">이미지는 내보내기에서 제외됨</p>'
        if path.is_file():
            mime = {'.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp'}.get(path.suffix.lower())
            require(mime is not None and path.stat().st_size <= 20 * 1024 ** 2, 'Unsupported/oversized report image')
            image = '<img loading="lazy" src="data:' + mime + ';base64,' + base64.b64encode(path.read_bytes()).decode() + '" alt="포스터 ' + escape(image_id, quote=True) + '">'
        cards.append('<article class="card"><h3>' + escape(image_id) + '</h3>' + image + '<p>' + escape(' · '.join(descriptions)) + '</p></article>')
    return '<p>선택 모델의 오답과 이전 모델 대비 개선·퇴행을 함께 표시합니다. unknown 라벨은 제외합니다.</p><div class="grid three cases">' + ''.join(cards) + '</div>' if cards else '<p>이 평가셋에서 알려진 라벨의 오류·판정 변경이 없습니다.</p>'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('evidence', type=Path)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--title', default='SigLIP2 학습·평가 결과서')
    parser.add_argument('--no-figures', action='store_true')
    args = parser.parse_args()
    print(build_report(args.evidence, args.out, args.title, not args.no_figures))


if __name__ == '__main__':
    main()
